  CONSTRAINT uq_reservation_status_label UNIQUE (label)
);

CREATE TABLE reservations (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
