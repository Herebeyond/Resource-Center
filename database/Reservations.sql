  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INT NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  user_id INT REFERENCES users(id) ON DELETE SET NULL,
  email VARCHAR(255),
  status VARCHAR(60) NOT NULL DEFAULT 'invited',
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_reservation_participants_user UNIQUE (reservation_id, user_id),
  CONSTRAINT uq_reservation_participants_email UNIQUE (reservation_id, email),
  CONSTRAINT chk_reservation_participant_target CHECK (user_id IS NOT NULL OR email IS NOT NULL)
);

CREATE TABLE vehicle_usage (
  reservation_id INT PRIMARY KEY REFERENCES reservations(id) ON DELETE CASCADE,
  vehicle_id INT NOT NULL REFERENCES resources(id) ON DELETE RESTRICT,
  checked_out_at TIMESTAMP,
  returned_at TIMESTAMP,
  issue_reported_at TIMESTAMP,
  issue_description TEXT,
  issue_resolved_at TIMESTAMP,
  CONSTRAINT chk_vehicle_usage_return CHECK (returned_at IS NULL OR checked_out_at IS NOT NULL)
