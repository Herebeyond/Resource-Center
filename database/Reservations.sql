-- Cohérence multi-entreprise: la réservation doit rester dans la même entreprise
CREATE OR REPLACE FUNCTION fn_check_reservation_company_consistency()
RETURNS TRIGGER AS $$
DECLARE
  v_user_company_id INT;
  v_resource_company_id INT;
BEGIN
  SELECT company_id INTO v_user_company_id FROM users WHERE id = NEW.user_id;
  IF v_user_company_id IS NULL THEN
    RAISE EXCEPTION 'Utilisateur % introuvable', NEW.user_id;
  END IF;

  SELECT company_id INTO v_resource_company_id FROM resources WHERE id = NEW.resource_id;
  IF v_resource_company_id IS NULL THEN
    RAISE EXCEPTION 'Ressource % introuvable', NEW.resource_id;
  END IF;

  IF NEW.company_id <> v_user_company_id OR NEW.company_id <> v_resource_company_id THEN
    RAISE EXCEPTION 'Incohérence entreprise: réservation(%) user(%) ressource(%)', NEW.company_id, v_user_company_id, v_resource_company_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reservation_company_consistency
BEFORE INSERT OR UPDATE OF company_id, user_id, resource_id ON reservations
FOR EACH ROW
EXECUTE FUNCTION fn_check_reservation_company_consistency();

-- Empêche les chevauchements sur une même ressource pour les statuts bloquants.
-- Le format '[)' signifie: début inclus, fin exclue.
-- Deux réservations adjacentes (ex: 10:00-11:00 et 11:00-12:00) ne sont pas en conflit.
CREATE OR REPLACE FUNCTION fn_prevent_reservation_overlap()
RETURNS TRIGGER AS $$
DECLARE
  v_is_blocking BOOLEAN;
BEGIN
  SELECT is_blocking INTO v_is_blocking
  FROM reservation_status
  WHERE id = NEW.status_id;

  IF COALESCE(v_is_blocking, FALSE) = FALSE THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM reservations r
    JOIN reservation_status rs ON rs.id = r.status_id
    WHERE r.resource_id = NEW.resource_id
      AND r.id <> COALESCE(NEW.id, -1)
      AND rs.is_blocking = TRUE
      AND tsrange(r.start_at, r.end_at, '[)') && tsrange(NEW.start_at, NEW.end_at, '[)')
  ) THEN
    RAISE EXCEPTION 'Conflit de réservation: chevauchement détecté pour la ressource %', NEW.resource_id;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM maintenance_events m
    WHERE m.resource_id = NEW.resource_id
      AND tsrange(m.start_at, m.end_at, '[)') && tsrange(NEW.start_at, NEW.end_at, '[)')
  ) THEN
    RAISE EXCEPTION 'Ressource % indisponible: créneau en maintenance', NEW.resource_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reservation_no_overlap
BEFORE INSERT OR UPDATE OF resource_id, start_at, end_at, status_id ON reservations
FOR EACH ROW
EXECUTE FUNCTION fn_prevent_reservation_overlap();

-- Empêche de planifier une maintenance qui chevauche des réservations bloquantes.
CREATE OR REPLACE FUNCTION fn_prevent_maintenance_overlap()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM reservations r
    JOIN reservation_status rs ON rs.id = r.status_id
    WHERE r.resource_id = NEW.resource_id
      AND rs.is_blocking = TRUE
      AND tsrange(r.start_at, r.end_at, '[)') && tsrange(NEW.start_at, NEW.end_at, '[)')
  ) THEN
    RAISE EXCEPTION 'Maintenance impossible: conflit avec des réservations actives sur la ressource %', NEW.resource_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_maintenance_no_overlap
BEFORE INSERT OR UPDATE OF resource_id, start_at, end_at ON maintenance_events
FOR EACH ROW
EXECUTE FUNCTION fn_prevent_maintenance_overlap();

