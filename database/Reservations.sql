-- Récupère l'utilisateur applicatif courant si l'application définit:
--   SET app.current_user_id = '123';
-- Sinon, retourne NULL.
CREATE OR REPLACE FUNCTION fn_current_actor_user_id()
RETURNS INT AS $$
DECLARE
  v_value TEXT;
BEGIN
  v_value := current_setting('app.current_user_id', TRUE);
  IF v_value IS NULL OR v_value = '' THEN
    RETURN NULL;
  END IF;
  RETURN v_value::INT;
EXCEPTION WHEN OTHERS THEN
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Historise les opérations INSERT/UPDATE/DELETE dans audit_logs.
-- p_entity_type: nom métier de l'entité (reservation, resource, maintenance, etc.)
-- p_company_expr: expression SQL qui renvoie company_id à partir de NEW/OLD.
CREATE OR REPLACE FUNCTION fn_audit_change()
RETURNS TRIGGER AS $$
DECLARE
  v_entity_type TEXT;
  v_company_id INT;
  v_entity_id INT;
  v_action TEXT;
  v_details JSONB;
BEGIN
  v_entity_type := TG_ARGV[0];
  v_company_id := NULL;
  v_entity_id := NULL;

  IF TG_OP = 'INSERT' THEN
    v_action := 'insert';
    v_details := jsonb_build_object('new', to_jsonb(NEW));
    v_entity_id := NEW.id;
  ELSIF TG_OP = 'UPDATE' THEN
    v_action := 'update';
    v_details := jsonb_build_object('old', to_jsonb(OLD), 'new', to_jsonb(NEW));
    v_entity_id := COALESCE(NEW.id, OLD.id);
  ELSE
    v_action := 'delete';
    v_details := jsonb_build_object('old', to_jsonb(OLD));
    v_entity_id := OLD.id;
  END IF;

  -- Résolution du company_id selon la table source.
  IF TG_TABLE_NAME = 'companies' THEN
    v_company_id := COALESCE(NEW.id, OLD.id);
  ELSIF TG_TABLE_NAME = 'users' THEN
    v_company_id := COALESCE(NEW.company_id, OLD.company_id);
  ELSIF TG_TABLE_NAME = 'resources' THEN
    v_company_id := COALESCE(NEW.company_id, OLD.company_id);
  ELSIF TG_TABLE_NAME = 'reservations' THEN
    v_company_id := COALESCE(NEW.company_id, OLD.company_id);
  ELSIF TG_TABLE_NAME = 'maintenance_events' THEN
    SELECT r.company_id
      INTO v_company_id
    FROM resources r
    WHERE r.id = COALESCE(NEW.resource_id, OLD.resource_id);
  ELSIF TG_TABLE_NAME = 'notifications' THEN
    SELECT u.company_id
      INTO v_company_id
    FROM users u
    WHERE u.id = COALESCE(NEW.user_id, OLD.user_id);
  END IF;

  INSERT INTO audit_logs (company_id, user_id, entity_type, entity_id, action, details, created_at)
  VALUES (
    v_company_id,
    fn_current_actor_user_id(),
    COALESCE(v_entity_type, TG_TABLE_NAME),
    v_entity_id,
    v_action,
    v_details,
    NOW()
  );

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- Historisation des tables métier les plus importantes.
CREATE TRIGGER trg_audit_resources
