  license_plate VARCHAR(30) NOT NULL,
  brand VARCHAR(120),
  model VARCHAR(120),
  fuel_type VARCHAR(80),
  vehicle_class VARCHAR(80),
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_vehicle_license_plate UNIQUE (license_plate)
