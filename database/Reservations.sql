CREATE TABLE companies (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_companies_name UNIQUE (name)
);

CREATE TABLE users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  first_name VARCHAR(120) NOT NULL,
  last_name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone_number VARCHAR(40),
  password_hash VARCHAR(255) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_users_company_email UNIQUE (company_id, email)
);

CREATE UNIQUE INDEX uq_users_email_global ON users (LOWER(email));

CREATE TABLE roles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  description TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_roles_name UNIQUE (name)
);

CREATE TABLE user_roles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id INT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_user_roles UNIQUE (user_id, role_id)
);

CREATE TABLE permissions (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  CONSTRAINT uq_permissions_name UNIQUE (name)
);

CREATE TABLE role_permissions (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id INT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_id INT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  CONSTRAINT uq_role_permissions UNIQUE (role_id, permission_id)
);

CREATE TABLE resource_types (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  description TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_resource_types_name UNIQUE (name)
);

CREATE TABLE resource_states (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label VARCHAR(120) NOT NULL,
  description TEXT,
  CONSTRAINT uq_resource_states_label UNIQUE (label)
);

CREATE TABLE resources (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  type_id INT NOT NULL REFERENCES resource_types(id) ON DELETE RESTRICT,
  state_id INT NOT NULL REFERENCES resource_states(id) ON DELETE RESTRICT,
  name VARCHAR(255) NOT NULL,
  code VARCHAR(80) NOT NULL,
  location VARCHAR(255),
  capacity INT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_resources_company_code UNIQUE (company_id, code),
  CONSTRAINT chk_resources_capacity_positive CHECK (capacity IS NULL OR capacity >= 0)
);

CREATE TABLE room_details (
  resource_id INT PRIMARY KEY REFERENCES resources(id) ON DELETE CASCADE,
